import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SIGN_CODES = ["B1", "B2", "B3", "B4", "B5", "B6", "B7", "C1", "G11", "G12a"] as const;
const USER_AGENT = "open-drive-theory/0.1 (educational; local asset import)";

interface ManifestEntry {
  code: string;
  file: string;
  commons_title: string;
  source_url: string;
  license: string;
}

function normalizeSvg(raw: string): string {
  const withoutScripts = raw.replace(/<script[\s\S]*?<\/script>/gi, "");
  const withoutDecl = withoutScripts.replace(/<\?xml[^?]*\?>/g, "").trim();
  const viewBoxMatch = withoutDecl.match(/viewBox\s*=\s*"([^"]+)"/i);
  let minX = 0;
  let minY = 0;
  let width = 100;
  let height = 100;
  if (viewBoxMatch?.[1]) {
    const parts = viewBoxMatch[1].trim().split(/[\s,]+/).map(Number);
    const boxX = parts[0];
    const boxY = parts[1];
    const boxWidth = parts[2];
    const boxHeight = parts[3];
    if (
      parts.length === 4 &&
      boxX !== undefined &&
      boxY !== undefined &&
      boxWidth !== undefined &&
      boxHeight !== undefined &&
      [boxX, boxY, boxWidth, boxHeight].every((part) => Number.isFinite(part)) &&
      boxWidth > 0 &&
      boxHeight > 0
    ) {
      minX = boxX;
      minY = boxY;
      width = boxWidth;
      height = boxHeight;
    }
  }
  const inner = withoutDecl.replace(/^<svg[^>]*>/i, "").replace(/<\/svg>\s*$/i, "");
  const scale = 84 / Math.max(width, height);
  const translateX = 50 - (minX + width / 2) * scale;
  const translateY = 50 - (minY + height / 2) * scale;
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100" width="100" height="100">`,
    `<g transform="translate(${translateX.toFixed(3)} ${translateY.toFixed(3)}) scale(${scale.toFixed(5)})">`,
    inner.trim(),
    `</g>`,
    `</svg>`,
    ``,
  ].join("\n");
}

function cleanUrl(url: string): string {
  const hash = url.split("?")[0];
  return hash ?? url;
}

async function commonsFiles(): Promise<Map<string, { url: string; license: string; title: string }>> {
  const titles = SIGN_CODES.map((code) => `File:Nederlands verkeersbord ${code}.svg`).join("|");
  const endpoint = new URL("https://commons.wikimedia.org/w/api.php");
  endpoint.searchParams.set("action", "query");
  endpoint.searchParams.set("format", "json");
  endpoint.searchParams.set("prop", "imageinfo");
  endpoint.searchParams.set("iiprop", "url|extmetadata");
  endpoint.searchParams.set("titles", titles);
  const response = await fetch(endpoint, { headers: { "User-Agent": USER_AGENT } });
  if (!response.ok) {
    throw new Error(`Commons API antwoordde ${response.status}`);
  }
  const body = (await response.json()) as {
    query?: { pages?: Record<string, { title?: string; missing?: boolean; imageinfo?: Array<{ url?: string; extmetadata?: { LicenseShortName?: { value?: string } } }> }> };
  };
  const found = new Map<string, { url: string; license: string; title: string }>();
  for (const page of Object.values(body.query?.pages ?? {})) {
    const info = page.imageinfo?.[0];
    const match = page.title?.match(/Nederlands verkeersbord ([A-Z0-9]+)\.svg$/i);
    const code = match?.[1]?.toUpperCase();
    if (!code || !info?.url || page.missing) {
      continue;
    }
    found.set(code, {
      url: info.url,
      license: info.extmetadata?.LicenseShortName?.value ?? "unknown",
      title: page.title ?? "",
    });
  }
  return found;
}

function libraryModule(signs: Record<string, string>): string {
  return `// SPDX-License-Identifier: AGPL-3.0-only
// Generated by scripts/fetch-assets.ts. Official sign artwork, no filesystem access.

export const OFFICIAL_SIGN_SVG: Readonly<Record<string, string>> = ${JSON.stringify(signs, null, 2)};
`;
}

async function main(): Promise<void> {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const directory = resolve(root, "assets");
  await mkdir(directory, { recursive: true });
  const remote = await commonsFiles();
  const manifest: ManifestEntry[] = [];
  const library: Record<string, string> = {};
  for (const code of SIGN_CODES) {
    const file = remote.get(code.toUpperCase());
    if (!file) {
      throw new Error(`Geen Commons-bestand voor ${code}`);
    }
    const response = await fetch(file.url, { headers: { "User-Agent": USER_AGENT } });
    if (!response.ok) {
      throw new Error(`Download mislukt voor ${code}: ${response.status}`);
    }
    const raw = await response.text();
    if (!raw.includes("<svg")) {
      throw new Error(`Geen SVG ontvangen voor ${code}`);
    }
    const normalized = normalizeSvg(raw);
    const fileName = `Nederlands_verkeersbord_${code}.svg`;
    await writeFile(resolve(directory, fileName), normalized, "utf8");
    library[`NL:${code}`] = normalized;
    manifest.push({
      code: `NL:${code}`,
      file: fileName,
      commons_title: file.title,
      source_url: cleanUrl(file.url),
      license: file.license,
    });
  }
  await writeFile(
    resolve(directory, "manifest.json"),
    `${JSON.stringify({ source: "Wikimedia Commons", signs: manifest }, null, 2)}\n`,
    "utf8",
  );
  await writeFile(resolve(root, "src/renderer/official_signs.ts"), libraryModule(library), "utf8");
}

await main();
